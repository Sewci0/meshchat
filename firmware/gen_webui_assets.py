#!/usr/bin/env python3
"""Embed the built MeshChat web app (webui/dist) into the firmware as gzip-compressed C arrays.

    python3 gen_webui_assets.py webui/dist <MeshCore>/examples/companion_radio/WebUiAssets.h

index.html comes first: the web server falls back to it for client-side routes.
Files under /assets/ are content-hashed by Vite, so they're served as immutable.
"""
import gzip, mimetypes, pathlib, re, sys

TYPES = {".js": "text/javascript", ".css": "text/css", ".html": "text/html; charset=utf-8",
         ".svg": "image/svg+xml", ".woff2": "font/woff2", ".png": "image/png", ".json": "application/json",
         ".webmanifest": "application/manifest+json"}

def main(src, dst):
    root = pathlib.Path(src)
    files = sorted(p for p in root.rglob("*") if p.is_file())
    files.sort(key=lambda p: p.name != "index.html")   # index.html first
    out = ["// Generated by meshchat/firmware/gen_webui_assets.py; do not edit.", "#pragma once", "#include <stddef.h>",
           "#include <stdint.h>", "",
           "struct WebAsset { const char* path; const char* type; const uint8_t* data; size_t len; bool immutable; };", ""]
    table, total_raw, total_gz = [], 0, 0
    for i, p in enumerate(files):
        rel = "/" + p.relative_to(root).as_posix()
        raw = p.read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total_raw += len(raw); total_gz += len(gz)
        name = f"WA_{i}_" + re.sub(r"[^A-Za-z0-9]", "_", p.name)[:40]
        body = ",".join(str(b) for b in gz)
        out.append(f"static const uint8_t {name}[] = {{{body}}};")
        ctype = TYPES.get(p.suffix, mimetypes.guess_type(p.name)[0] or "application/octet-stream")
        table.append(f'  {{"{rel}", "{ctype}", {name}, sizeof({name}), {"true" if rel.startswith("/assets/") else "false"}}},')
    out += ["", "static const WebAsset WEB_ASSETS[] = {", *table, "};",
            "static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);", ""]
    pathlib.Path(dst).write_text("\n".join(out))
    print(f"{len(files)} files, {total_raw/1024:.0f} KB -> {total_gz/1024:.0f} KB gzip -> {dst}")

if __name__ == "__main__":
    main(*sys.argv[1:3])
